//! UI language. English strings are the keys; `t` returns the French text when French is active.

use std::sync::atomic::{AtomicBool, Ordering};

static FRENCH: AtomicBool = AtomicBool::new(false);

/// "fr" or "en".
pub fn set_language(lang: &str) {
    FRENCH.store(lang == "fr", Ordering::Relaxed);
    gpui_kit::component::set_locale(if lang == "fr" { "fr" } else { "en" });
}

/// Default language from the environment.
pub fn system_language() -> &'static str {
    let lang = std::env::var("LANG").or_else(|_| std::env::var("LC_ALL")).unwrap_or_default();
    if lang.starts_with("fr") { "fr" } else { "en" }
}

pub fn t(s: &'static str) -> &'static str {
    if !FRENCH.load(Ordering::Relaxed) {
        return s;
    }
    french(s).unwrap_or(s)
}

